window.FY_LANG = (function () {
  const EN = window.FY_EN;
  const ATTRS = ['alt', 'aria-label', 'placeholder'];
  const SKIP = 'script,style,svg,[data-noi18n]';
  let lang = 'es';
  const nodes = [];
  function collect() {
    const w = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
      acceptNode: n => (n.parentElement.closest(SKIP) ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT)
    });
    let n;
    while ((n = w.nextNode())) {
      const key = n.nodeValue.trim().replace(/\s+/g, ' ');
      if (EN[key]) nodes.push({ n, es: n.nodeValue, key });
    }
    document.querySelectorAll('*').forEach(el => {
      if (el.closest(SKIP)) return;
      ATTRS.forEach(a => {
        const v = el.getAttribute(a);
        if (v && EN[v]) nodes.push({ el, a, es: v, key: v });
      });
    });
  }
  function t(s) { return lang === 'en' && EN[s] ? EN[s] : s; }
  function apply(l) {
    lang = l;
    nodes.forEach(x => {
      const val = l === 'en' ? EN[x.key] : x.key;
      if (x.n) x.n.nodeValue = x.es.replace(x.es.trim(), val);
      else x.el.setAttribute(x.a, l === 'en' ? EN[x.key] : x.es);
    });
    document.documentElement.lang = l;
    document.title = l === 'en' ? 'FY Business & Immigration Solutions | Atlanta' : 'FY Business & Immigration Solutions | Atlanta';
    const b = document.getElementById('lang-btn');
    if (b) {
      b.textContent = l === 'en' ? 'ES' : 'EN';
      b.setAttribute('aria-label', l === 'en' ? 'Cambiar a español' : 'Switch to English');
    }
    try { localStorage.setItem('fy-lang', l); } catch (e) {}
    document.dispatchEvent(new CustomEvent('fy:lang', { detail: l }));
  }
  function init() {
    collect();
    let saved = null;
    try { saved = localStorage.getItem('fy-lang'); } catch (e) {}
    apply(saved === 'en' ? 'en' : 'es');
    document.getElementById('lang-btn')?.addEventListener('click', () => apply(lang === 'es' ? 'en' : 'es'));
  }
  return { init, t, get: () => lang };
})();
